/**
 * Extracts the vendored web fonts from the design export.
 *
 * The export in `design/` is a self-contained page: every asset it needs is base64 in a
 * `__bundler/manifest` block, and the page's own HTML is a JSON string in a `__bundler/template`
 * block. The template carries the Google Fonts stylesheet the design was drawn with, its `url()`
 * targets rewritten to manifest ids.
 *
 * This script pulls those font files out and rewrites that stylesheet to point at local files, so
 * the app never asks a CDN for a font — the shop's machine has no internet access.
 *
 * Output (both committed):
 *   src/assets/fonts/*.woff2
 *   src/styles/fonts.css
 *
 * `npm run fonts:extract` writes them. `npm run fonts:check` regenerates in memory and fails if
 * what is committed differs, so a hand-edited stylesheet or a swapped design export turns the
 * repository red rather than shipping a font nobody can trace.
 */

import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXPORT = path.join(root, 'design', 'Shopbook_Daily.html');
const FONT_DIR = path.join(root, 'src', 'assets', 'fonts');
const CSS_FILE = path.join(root, 'src', 'styles', 'fonts.css');

/** Reads one of the export's `<script type="__bundler/*">` payloads. */
function bundlerSection(html, type) {
  const open = `<script type="__bundler/${type}">`;
  const start = html.indexOf(open);
  if (start < 0) throw new Error(`design export has no "${type}" section`);
  const from = start + open.length;
  const end = html.indexOf('</script>', from);
  if (end < 0) throw new Error(`design export's "${type}" section is unterminated`);
  return html.slice(from, end).trim();
}

function slug(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

const html = fs.readFileSync(EXPORT, 'utf8');
const manifest = JSON.parse(bundlerSection(html, 'manifest'));
const template = JSON.parse(bundlerSection(html, 'template'));

// Google Fonts emits one `/* subset */` comment per @font-face, which is the only name the subset
// ever gets — the unicode-range alone would make an unreadable filename.
const FACE = /\/\*\s*([^*]+?)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
const descriptor = (block, name) => {
  const found = new RegExp(`(?:^|;)\\s*${name}\\s*:\\s*([^;]+)`, 'i').exec(block);
  return found ? found[1].trim() : null;
};

const faces = [];
const files = new Map(); // manifest id -> filename

for (const [, subset, block] of template.matchAll(FACE)) {
  const family = descriptor(block, 'font-family');
  const src = /url\("([^"]+)"\)/.exec(descriptor(block, 'src') ?? '');
  if (!family || !src) throw new Error(`@font-face without a family or a source: ${block}`);

  const id = src[1];
  const asset = manifest[id];
  if (!asset) throw new Error(`@font-face points at ${id}, which the manifest does not contain`);
  if (asset.mime !== 'font/woff2') throw new Error(`${id} is ${asset.mime}, not font/woff2`);

  if (!files.has(id)) {
    files.set(id, `${slug(family)}-${slug(subset)}.woff2`);
  }
  faces.push({
    subset,
    family,
    style: descriptor(block, 'font-style') ?? 'normal',
    weight: descriptor(block, 'font-weight') ?? '400',
    display: descriptor(block, 'font-display') ?? 'swap',
    unicodeRange: descriptor(block, 'unicode-range'),
    file: files.get(id),
  });
}

const binaries = new Map();
let bytes = 0;
for (const [id, file] of files) {
  const asset = manifest[id];
  let data = Buffer.from(asset.data, 'base64');
  if (asset.compressed) data = zlib.gunzipSync(data);
  binaries.set(file, data);
  bytes += data.length;
}

const css = [
  '/*',
  ' * Generated by scripts/extract-design-fonts.mjs from design/Shopbook_Daily.html.',
  ' * Do not edit by hand — re-run `npm run fonts:extract` instead.',
  ' *',
  ' * Each family is a variable font cut into unicode-range subsets, so a device downloads only',
  ' * the scripts it actually renders. Every file is served from this repository; nothing here',
  ' * reaches a CDN.',
  ' */',
  '',
  ...faces.map((face) =>
    [
      `/* ${face.family} ${face.weight} — ${face.subset} */`,
      '@font-face {',
      `  font-family: ${face.family};`,
      `  font-style: ${face.style};`,
      `  font-weight: ${face.weight};`,
      `  font-display: ${face.display};`,
      `  src: url('../assets/fonts/${face.file}') format('woff2');`,
      ...(face.unicodeRange ? [`  unicode-range: ${face.unicodeRange};`] : []),
      '}',
      '',
    ].join('\n'),
  ),
].join('\n');

const summary = `${files.size} font files (${Math.round(bytes / 1024)} KB) and ${faces.length} @font-face rules`;
const families = [...new Set(faces.map((face) => face.family.replace(/'/g, '')))];

if (process.argv.includes('--check')) {
  const committed = fs.existsSync(FONT_DIR) ? fs.readdirSync(FONT_DIR).sort() : [];
  const problems = [];

  for (const name of committed) {
    if (!binaries.has(name))
      problems.push(`${name} is committed but the design export has no such font`);
  }
  for (const [name, data] of binaries) {
    const file = path.join(FONT_DIR, name);
    if (!fs.existsSync(file)) problems.push(`${name} is missing`);
    else if (!fs.readFileSync(file).equals(data))
      problems.push(`${name} differs from the design export`);
  }
  if (!fs.existsSync(CSS_FILE)) problems.push('src/styles/fonts.css is missing');
  else if (fs.readFileSync(CSS_FILE, 'utf8') !== css) {
    problems.push('src/styles/fonts.css differs from what the design export produces');
  }

  if (problems.length > 0) {
    console.error('The vendored fonts do not match design/Shopbook_Daily.html:');
    for (const problem of problems) console.error(`  - ${problem}`);
    console.error('\nRun `npm run fonts:extract` and commit the result.');
    process.exit(1);
  }
  console.log(`vendored fonts match the design export — ${summary}`);
} else {
  // Rewritten from scratch each run, so a font dropped from the design leaves no orphan behind.
  fs.rmSync(FONT_DIR, { recursive: true, force: true });
  fs.mkdirSync(FONT_DIR, { recursive: true });
  for (const [name, data] of binaries) fs.writeFileSync(path.join(FONT_DIR, name), data);

  fs.mkdirSync(path.dirname(CSS_FILE), { recursive: true });
  fs.writeFileSync(CSS_FILE, css);

  console.log(summary);
  console.log(`families: ${families.join(', ')}`);
}
